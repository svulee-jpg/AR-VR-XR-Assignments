"""
generate_textures.py - procedural, seamlessly tiling textures for PA4 (Winter steppe).

Why this script exists: the textures are generated by code, so they are original work
and can be released under CC0 1.0 (public domain). No third-party images are used.

How to run (from the PA4 folder):
    python3 -m pip install numpy pillow
    python3 tools/generate_textures.py

Output (all 1024 x 1024 px, well under the 10 MB project limit):
    textures/snow.jpg         snow with dry steppe grass specks   (ground, colour map)
    textures/snow_normal.jpg  bumpy normal map for the snow       (ground, normal map)
    textures/ice.jpg          frosted blue ice                     (frozen path)
    textures/wood.jpg         vertical wooden planks              (end wall)

Key idea: noise is made in the frequency domain (FFT). Filtered white noise made this way
is periodic, so the left edge continues into the right edge and `repeat` has no visible seams.
"""
import os
import numpy as np
from PIL import Image

N = 1024
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "textures")
os.makedirs(OUT, exist_ok=True)


def periodic_noise(beta, seed, stretch_y=1.0):
    """Tileable noise in [0, 1]. beta = 'roughness' (bigger -> smoother blobs).
    stretch_y < 1 stretches the pattern vertically (used for wood grain)."""
    rng = np.random.default_rng(seed)
    white = rng.standard_normal((N, N))
    spectrum = np.fft.fft2(white)
    fy = np.fft.fftfreq(N)[:, None] * stretch_y
    fx = np.fft.fftfreq(N)[None, :]
    f = np.sqrt(fx ** 2 + fy ** 2)
    f[0, 0] = 1.0
    spectrum *= f ** (-beta / 2.0)
    spectrum[0, 0] = 0.0
    field = np.fft.ifft2(spectrum).real
    field -= field.min()
    field /= field.max()
    return field


def save_jpg(array, name, quality=88):
    img = Image.fromarray((np.clip(array, 0, 1) * 255).astype(np.uint8), "RGB")
    path = os.path.join(OUT, name)
    img.save(path, "JPEG", quality=quality, optimize=True)
    print("wrote", path, os.path.getsize(path) // 1024, "KB")


def make_snow():
    low = periodic_noise(2.6, 1)       # soft drifts
    mid = periodic_noise(1.6, 2)       # medium bumps
    fine = periodic_noise(0.4, 3)      # fine grain (this is what shimmers when filtering is bad)
    base = 0.86 + 0.10 * (low - 0.5) + 0.05 * (mid - 0.5) + 0.05 * (fine - 0.5)
    rgb = np.stack([base * 0.97, base * 0.99, base * 1.02], axis=-1)

    # Dry steppe grass poking through the snow: sparse small dark-yellow specks.
    speck = periodic_noise(0.2, 4)
    cut = np.percentile(speck, 99.2)          # darkest ~0.8 % of pixels become grass specks
    mask = np.clip((speck - cut) / 0.03, 0, 1)[..., None]
    grass = np.array([0.52, 0.46, 0.30])
    rgb = rgb * (1 - mask * 0.85) + grass * mask * 0.85

    # A few bright sparkles.
    sparkle = periodic_noise(0.1, 5)
    cut = np.percentile(sparkle, 99.7)
    rgb += (np.clip((sparkle - cut) / 0.03, 0, 1) * 0.15)[..., None]
    return rgb


def make_snow_normal():
    height = 0.8 * periodic_noise(2.6, 6) + 0.2 * periodic_noise(1.8, 7)
    strength = 2.0
    dx = (np.roll(height, -1, axis=1) - np.roll(height, 1, axis=1)) * 0.5 * N / 64
    dy = (np.roll(height, -1, axis=0) - np.roll(height, 1, axis=0)) * 0.5 * N / 64
    nx, ny, nz = -dx * strength, dy * strength, np.ones_like(height)
    length = np.sqrt(nx ** 2 + ny ** 2 + nz ** 2)
    normal = np.stack([nx / length, ny / length, nz / length], axis=-1)
    return normal * 0.5 + 0.5


def make_ice():
    shade = periodic_noise(2.4, 8)
    base = np.stack([0.50 + 0.15 * shade, 0.70 + 0.14 * shade, 0.86 + 0.08 * shade], axis=-1)
    # Frost veins = places where a smooth noise field crosses its middle value.
    cracks = np.zeros((N, N))
    for seed, width in ((9, 0.012), (10, 0.008)):
        field = periodic_noise(2.0, seed)
        field = (field - np.median(field)) / field.std()      # 0 = the crack line
        cracks = np.maximum(cracks, np.exp(-(field / (width * 8)) ** 2))
    bubbles = np.clip((periodic_noise(0.6, 11) - 0.9) / 0.1, 0, 1)
    rgb = base * (1 - 0.85 * cracks[..., None]) + np.array([0.93, 0.98, 1.0]) * 0.85 * cracks[..., None]
    rgb += 0.10 * bubbles[..., None]
    return rgb


def make_wood():
    planks = 8
    width = N // planks
    grain = periodic_noise(1.8, 12, stretch_y=0.06)      # long vertical streaks
    knots = periodic_noise(2.4, 13)
    rng = np.random.default_rng(14)
    tone = rng.uniform(0.85, 1.15, planks)
    column = np.repeat(tone, width)[None, :] * np.ones((N, 1))
    light = (0.62 + 0.55 * (grain - 0.5) + 0.12 * (knots - 0.5)) * column
    rgb = np.stack([0.62 * light * 1.25, 0.42 * light * 1.25, 0.25 * light * 1.25], axis=-1)
    # Dark seams between planks (positions are multiples of `width`, so the tile still repeats).
    x = np.arange(N)[None, :] % width
    seam = np.clip(1 - np.minimum(x, width - x) / 3.0, 0, 1)
    rgb *= (1 - 0.65 * seam[..., None] * np.ones((N, 1, 1)))
    return rgb


if __name__ == "__main__":
    save_jpg(make_snow(), "snow.jpg")
    save_jpg(make_snow_normal(), "snow_normal.jpg", quality=92)
    save_jpg(make_ice(), "ice.jpg")
    save_jpg(make_wood(), "wood.jpg")
